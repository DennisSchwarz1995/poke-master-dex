/**
 * Seeds isolated showcase Pokédex data for anonymous live demo sessions
 * and cleans up temporary Firestore documents on demo exit.
 */
@Injectable({
  providedIn: 'root',
})
export class DemoSeedService {
  private readonly firestoreService = inject(FirestoreService);
  private readonly datasetService = inject(DatasetService);

  async seedDemoAccount(userId: string): Promise<string | null> {
    const existingDexes = await firstValueFrom(this.firestoreService.getUserDexList());
    if (existingDexes.length > 0) {
      return existingDexes[0].id;
    }

    const [, , pokemonMapping, boxNames] = await Promise.all([
      this.firestoreService.createTrainer({
        name: 'Red',
        trainerId: '001996',
        secretId: '04215',
        gender: 'male',
        game: 'sv-v',
      }),
      this.firestoreService.createTrainer({
        name: 'Akari',
        trainerId: '482910',
        gender: 'female',
        game: 'la',
      }),
      firstValueFrom(this.datasetService.createDexMapping(DexType.LIVING, 'grouped')),
      firstValueFrom(this.datasetService.getDexBoxNames(DexType.LIVING, 'grouped')),
    ]);

    const dexId = await this.firestoreService.createDex(
      {
        name: 'Living Dex (Demo)',
        type: DexType.LIVING,
        description:
          'Pre-filled showcase Pokédex with sample Pokémon, Shinies, Moves, IVs/EVs, Ribbons & Trainers.',
        startBox: 1,
        totalBoxes: 200,
      },
      true,
    );

    await this.firestoreService.initializeBoxes(
      userId,
      dexId,
      1,
      pokemonMapping,
      boxNames,
      DEMO_SLOT_OVERRIDES,
    );

    return dexId;
  }

  async cleanupDemoAccount(): Promise<void> {
    try {
      const [dexes, trainers] = await Promise.all([
        firstValueFrom(this.firestoreService.getUserDexList()),
        firstValueFrom(this.firestoreService.getUserTrainers()),
      ]);

      await Promise.allSettled([
        ...dexes.map((dex) => this.firestoreService.deleteDex(dex.id, true)),
        ...trainers.map((trainer) => this.firestoreService.deleteTrainer(trainer.id)),
      ]);
    } catch (err) {
      console.error('Failed to clean up demo account data:', err);
    }
  }
}
