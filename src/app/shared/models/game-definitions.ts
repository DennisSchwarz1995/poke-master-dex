export function getGameName(code: string): string {
  return GAME_CODES[code]?.fullName || code;
}

export function getAvailableGamesForPokemon(storableIn: string[]): GameDefinition[] {
  return storableIn
    .map((code) => GAME_CODES[code])
    .filter((game) => game !== undefined)
    .sort((a, b) => {
      if (a.gen !== b.gen) return b.gen - a.gen;
      return b.year - a.year;
    });
}
